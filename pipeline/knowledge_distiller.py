# ============================================================
# Teacher Backend Interface
# ============================================================
class TeacherBackend:
    def generate(self, system: str, user: str) -> str:
        raise NotImplementedError


class OpenCodeTeacher(TeacherBackend):
    def generate(self, system: str, user: str) -> str:
        print("[Teacher] OpenCode mode: dataset will be generated by the assistant.")
        print(
            "[Teacher] Run 'python pipeline/knowledge_distiller.py --generate' to signal the assistant."
        )
        return ""


class OpenRouterTeacher(TeacherBackend):
    def __init__(self, config):
        self.api_key = os.getenv("TEACHER_API_KEY", config.get("api_key", ""))
        self.model = config.get("model", "qwen/qwen3-32b")
        self.base_url = config.get("api_base", "https://openrouter.ai/api/v1")

    def generate(self, system: str, user: str) -> str:
        import requests

        resp = requests.post(
            f"{self.base_url}/chat/completions",
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json",
            },
            json={
                "model": self.model,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
                "temperature": 0.3,
                "max_tokens": 2048,
            },
            timeout=120,
        )
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"]


