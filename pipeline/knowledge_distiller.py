class HuggingFaceTeacher(TeacherBackend):
    def __init__(self, config):
        self.api_key = os.getenv("TEACHER_API_KEY", config.get("api_key", ""))
        self.model = config.get("model", "Qwen/Qwen3-32B-Instruct")

    def generate(self, system: str, user: str) -> str:
        import requests

        headers = {"Authorization": f"Bearer {self.api_key}"}
        payload = {
            "inputs": f"<|im_start|>system\n{system}<|im_end|>\n<|im_start|>user\n{user}<|im_end|>\n<|im_start|>assistant\n",
            "parameters": {"max_new_tokens": 2048, "temperature": 0.3},
        }
        resp = requests.post(
            f"https://api-inference.huggingface.co/models/{self.model}",
            headers=headers,
            json=payload,
            timeout=120,
        )
        resp.raise_for_status()
        return resp.json()[0]["generated_text"]


